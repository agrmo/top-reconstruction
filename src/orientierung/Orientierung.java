package orientierung;

// Eine Orientierung ist ein Triplett von
// - Zahl
// - Zahl
// - Zahl
public class Orientierung {
    double winkeleins;
    double winkelzwei;
    double winkeldrei;

    public Orientierung(double winkeleins,
			double winkelzwei,
			double winkeldrei) {
	
	this.winkeleins = winkeleins;
	this.winkelzwei = winkelzwei;
	this.winkeldrei = winkeldrei;
    }
}
